"""FreeCAD integration helpers.

FreeCAD is an optional external dependency and is never imported during
normal package startup.
"""
from __future__ import annotations

import math
import re
import subprocess
from pathlib import Path


def _validate_dimensions(radius_mm: float, height_mm: float) -> None:
    for name, value in (("radius_mm", radius_mm), ("height_mm", height_mm)):
        if not isinstance(value, (int, float)) or not math.isfinite(value) or value <= 0:
            raise ValueError(f"{name} must be a finite positive number")


def build_cylinder_macro(*, radius_mm: float, height_mm: float,
                         output_dir: str | Path,
                         basename: str = "yj64_cylinder") -> str:
    """Build a FreeCAD macro for a parametric cylinder and STEP/STL exports.

    Generates source only. It does not execute FreeCAD.
    """
    _validate_dimensions(radius_mm, height_mm)
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", basename):
        raise ValueError("basename may contain only letters, digits, '_' and '-'")

    target = Path(output_dir).expanduser().resolve()
    target.mkdir(parents=True, exist_ok=True)
    fcstd_path = str(target / f"{basename}.FCStd")
    step_path = str(target / f"{basename}.step")
    stl_path = str(target / f"{basename}.stl")

    return f'''# Generated by YJ64 Engineering Core. Review before running.
import FreeCAD as App
import Part
import Import
import Mesh

doc = App.newDocument("YJ64_Cylinder")
cylinder = doc.addObject("Part::Cylinder", "Cylinder")
cylinder.Label = "Parametric cylinder"
cylinder.Radius = {float(radius_mm)!r}
cylinder.Height = {float(height_mm)!r}
doc.recompute()
Import.export([cylinder], {step_path!r})
Mesh.export([cylinder], {stl_path!r})
doc.saveAs({fcstd_path!r})
App.closeDocument(doc.Name)
'''


def run_freecad_macro(*, executable: str | Path, macro_path: str | Path,
                      timeout_seconds: int = 120) -> subprocess.CompletedProcess[str]:
    """Run a reviewed macro with FreeCADCmd; never invokes a shell."""
    if not isinstance(timeout_seconds, int) or not 1 <= timeout_seconds <= 3600:
        raise ValueError("timeout_seconds must be between 1 and 3600")
    macro = Path(macro_path).expanduser().resolve()
    if not macro.is_file():
        raise FileNotFoundError(f"FreeCAD macro does not exist: {macro}")
    return subprocess.run(
        [str(Path(executable).expanduser()), str(macro)],
        check=True, capture_output=True, text=True,
        timeout=timeout_seconds, shell=False,
    )
