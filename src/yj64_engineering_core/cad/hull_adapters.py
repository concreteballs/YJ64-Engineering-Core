"""Workspace-bound multi-artifact CAD backend for parametric yacht hulls."""
from __future__ import annotations

import hashlib
import re
import subprocess
from pathlib import Path
from urllib.parse import unquote, urlparse
from typing import Any

from .hull import YachtHull, yacht_hull_openscad, yacht_hull_technical_svg, hull_vertices_mm


def build_hull_freecad_macro(hull: YachtHull, output_dir: str | Path, basename: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", basename):
        raise ValueError("basename may contain only letters, digits, '_' and '-'")
    target = Path(output_dir).expanduser().resolve()
    sections = []
    for station in hull.stations:
        x = station.x_m * 1000.0
        beam = station.half_beam_m * 1000.0
        fraction = hull.chine_fraction
        sections.append([
            (x, 0.0, station.keel_z_m * 1000.0),
            (x, beam*fraction, station.chine_z_m * 1000.0),
            (x, beam, station.deck_z_m * 1000.0),
            (x, -beam, station.deck_z_m * 1000.0),
            (x, -beam*fraction, station.chine_z_m * 1000.0),
        ])
    section_text = repr(sections)
    fcstd = str(target / f"{basename}.FCStd")
    step = str(target / f"{basename}.step")
    stl = str(target / f"{basename}.stl")
    return f'''# Generated by YJ64 Engineering Core. Review before running.
# Outer hull envelope only; no structural laminate or scantling model.
import FreeCAD as App
import Part
import Import
import Mesh

sections = {section_text}
doc = App.newDocument("YJ64_Yacht_Hull")
wires = []
for section in sections:
    points = [App.Vector(*point) for point in section]
    points.append(points[0])
    wires.append(Part.Wire(Part.makePolygon(points).Edges))
hull_shape = Part.makeLoft(wires, True, False)
obj = doc.addObject("PartDesign::Feature", "HullEnvelope")
obj.Label = "Parametric outer hull envelope"
obj.Shape = hull_shape
doc.recompute()
Import.export([obj], {step!r})
Mesh.export([obj], {stl!r})
doc.saveAs({fcstd!r})
App.closeDocument(doc.Name)
'''


class YachtHullCADBackend:
    """Generate SVG, editable OpenSCAD, and FreeCAD macro artifacts.

    If an OpenSCAD executable is supplied, it also renders a real STL mesh.
    """
    name = "YJ64 parametric yacht hull CAD"
    version = "0.2.0"

    def __init__(self, workspace: str | Path, openscad_executable: str | Path | None = None,
                 render_stl: bool = False, timeout_seconds: int = 120) -> None:
        self.workspace = Path(workspace).expanduser().resolve()
        self.workspace.mkdir(parents=True, exist_ok=True)
        self.openscad_executable = str(openscad_executable) if openscad_executable else None
        self.render_stl = render_stl
        if render_stl and not self.openscad_executable:
            raise ValueError("render_stl requires an explicit OpenSCAD executable")
        if not isinstance(timeout_seconds, int) or not 1 <= timeout_seconds <= 900:
            raise ValueError("timeout_seconds must be between 1 and 900")
        self.timeout_seconds = timeout_seconds

    def supported_formats(self) -> tuple[str, ...]:
        return ("svg", "scad", "FCMacro", "stl")

    def generate(self, specification: dict[str, Any]) -> dict[str, Any]:
        if specification.get("geometry_type") != "yacht_hull":
            raise ValueError("YachtHullCADBackend supports yacht_hull geometry only")
        request_id = specification.get("request_id", "yacht-hull")
        basename = re.sub(r"[^A-Za-z0-9_-]", "_", request_id)[:64] or "yacht_hull"
        hull = YachtHull.from_parameters(specification.get("parameters", {}))
        outputs: list[dict[str, str]] = []

        svg_path = self.workspace / f"{basename}.svg"
        svg_path.write_text(yacht_hull_technical_svg(hull), encoding="utf-8")
        outputs.append({"format": "image/svg+xml", "location": svg_path.as_uri()})

        scad_path = self.workspace / f"{basename}.scad"
        scad_path.write_text(yacht_hull_openscad(hull), encoding="utf-8")
        outputs.append({"format": "application/x-openscad", "location": scad_path.as_uri()})

        macro_path = self.workspace / f"{basename}.FCMacro"
        macro_path.write_text(
            build_hull_freecad_macro(hull, self.workspace, basename), encoding="utf-8"
        )
        outputs.append({"format": "text/x-freecad-macro", "location": macro_path.as_uri()})

        warnings = [
            "Outer hull envelope only; internal structure, laminate, stiffeners and scantlings are not modelled.",
            "2D drawing is a preliminary technical sketch, not a production drawing.",
        ]
        if self.render_stl:
            stl_path = self.workspace / f"{basename}.stl"
            env = {"QT_QPA_PLATFORM": "offscreen"}
            result = subprocess.run(
                [self.openscad_executable, "-o", str(stl_path), str(scad_path)],
                cwd=self.workspace, capture_output=True, text=True,
                timeout=self.timeout_seconds, shell=False, env=__import__("os").environ | env,
            )
            if result.returncode != 0 or not stl_path.is_file() or stl_path.stat().st_size < 84:
                raise RuntimeError(
                    "OpenSCAD STL render failed: " + (result.stderr or result.stdout)[-2000:]
                )
            outputs.append({"format": "model/stl", "location": stl_path.as_uri()})
        else:
            warnings.append("STL mesh not rendered; provide an OpenSCAD executable to enable it.")

        for item in outputs:
            artifact_path = Path(unquote(urlparse(item["location"]).path))
            item["sha256"] = hashlib.sha256(artifact_path.read_bytes()).hexdigest()

        return {
            "format": "application/vnd.yj64.cad-artifact-set",
            "location": scad_path.as_uri(),
            "artifacts": outputs,
            "warnings": warnings,
            "limitations": [
                "FreeCAD macro is generated but not executed by this backend.",
                "Hull stations describe an outer envelope; they do not define a build-ready hull structure.",
            ],
        }
